function autoSize(f){
  const sample='가나다라ABCabc123';let best=null;
  for(let s=8;s<=32;s++){
    sctx.font=`${s}px "${f.family}"`;const w=Math.ceil(sctx.measureText(sample).width)+4,hh=s*2;
    scratch.width=w;scratch.height=hh;sctx.font=`${s}px "${f.family}"`;sctx.textBaseline='middle';sctx.fillText(sample,2,s);
    const d=sctx.getImageData(0,0,w,hh).data;let ink=0,gray=0;
    for(let i=3;i<d.length;i+=4){if(d[i]){ink++;if(d[i]<250)gray++}}
    const score=ink?gray/ink:1;
    if(!best||score<best.score-0.01) best={s,score};
  }
  return best&&best.score<0.35?best.s:16;
}
