function makeBuiltin(id,name,map,rows,base,spaceW){
  const g={};
  for(const [ch,src] of Object.entries(map)){
    const rs=src.split('|'); const w=rs[0].length;
    while(rs.length<rows) rs.push('.'.repeat(w));
    const bits=new Uint8Array(w*rows);
    rs.forEach((r,y)=>{for(let x=0;x<w;x++) if(r[x]==='#') bits[y*w+x]=1});
    g[ch]={w,h:rows,base,bits};
  }
  g[' ']={w:spaceW,h:rows,base,bits:new Uint8Array(spaceW*rows)};
  return {id,name,kind:'builtin',glyph(ch){return g[ch]||g[ch.toUpperCase()]||null}};
}

