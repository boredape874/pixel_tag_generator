function ttfFontStr(f,extra){return `${f.size}px "${f.family}"${extra?', '+extra:''}`}
function ttfHas(f,ch){
  if(/\s/.test(ch)) return true;
  const ws=['monospace','serif','sans-serif'].map(fb=>{sctx.font=ttfFontStr(f,fb);return sctx.measureText(ch).width});
  return ws[0]===ws[1]&&ws[1]===ws[2];
}
function ttfGlyph(f,ch){
  if(f.cache.has(ch)) return f.cache.get(ch);
  let g=null;
  if(ttfHas(f,ch)){
    sctx.font=ttfFontStr(f);
    const m=sctx.measureText(ch);
    const adv=Math.max(0,Math.round(m.width));
    const asc=Math.ceil(m.fontBoundingBoxAscent??f.size*0.8), desc=Math.ceil(m.fontBoundingBoxDescent??f.size*0.2);
    const pad=Math.ceil(f.size/2), W=adv+pad*2, H=Math.max(1,asc+desc);
    scratch.width=Math.max(1,W); scratch.height=H;
    sctx.clearRect(0,0,W,H); sctx.font=ttfFontStr(f); sctx.textBaseline='alphabetic'; sctx.fillStyle='#000';
    sctx.fillText(ch,pad,asc);
    const d=sctx.getImageData(0,0,Math.max(1,W),H).data;
    const on=(x,y)=>d[(y*W+x)*4+3]>=f.threshold;
    let x0=W,x1=-1;
    for(let y=0;y<H;y++)for(let x=0;x<W;x++) if(on(x,y)){if(x<x0)x0=x;if(x>x1)x1=x}
    if(x1<0||!f.trim){x0=pad;x1=pad+adv-1}
    const w=Math.max(0,x1-x0+1), bits=new Uint8Array(w*H);
    for(let y=0;y<H;y++)for(let x=0;x<w;x++){const sx=x0+x;if(sx>=0&&sx<W&&on(sx,y))bits[y*w+x]=1}
    g={w,h:H,base:asc-f.baseAdj,bits};
  }
  f.cache.set(ch,g); return g;
}
function sheetGlyph(f,ch){
  if(f.cache.has(ch)) return f.cache.get(ch);
  let g=null; const cp=ch.codePointAt(0);
  const img=cp<=0xFFFF?f.pages.get(cp>>8):null;
  if(img){
    const cw=img.w/16|0, chh=img.h/16|0, idx=cp&255, ox=(idx%16)*cw, oy=(idx>>4)*chh;
    const on=(x,y)=>img.d[((oy+y)*img.w+ox+x)*4+3]>=f.threshold;
    let x0=cw,x1=-1;
    for(let y=0;y<chh;y++)for(let x=0;x<cw;x++) if(on(x,y)){if(x<x0)x0=x;if(x>x1)x1=x}
    const base=Math.round(chh*0.875)-f.baseAdj;
    if(x1<0){ if(/\s/.test(ch)){const w=Math.max(1,Math.round(cw*0.5));g={w,h:chh,base,bits:new Uint8Array(w*chh)}} }
    else{
      if(!f.trim) x0=0;
      const w=x1-x0+1, bits=new Uint8Array(w*chh);
      for(let y=0;y<chh;y++)for(let x=0;x<w;x++) if(on(x0+x,y)) bits[y*w+x]=1;
      g={w,h:chh,base,bits};
    }
  }
  if(!g&&/\s/.test(ch)&&f.pages.size){const any=[...f.pages.values()][0];const chh=any.h/16|0;const w=Math.max(1,Math.round(any.w/32));g={w,h:chh,base:Math.round(chh*0.875)-f.baseAdj,bits:new Uint8Array(w*chh)}}
  f.cache.set(ch,g); return g;
}
function makeUserFont(rec){
  const f={id:rec.id,name:rec.name,kind:rec.kind,size:rec.size||16,threshold:rec.threshold||128,baseAdj:rec.baseAdj||0,trim:rec.trim!==false,cache:new Map(),rec};
  f.glyph=ch=>f.kind==='ttf'?ttfGlyph(f,ch):sheetGlyph(f,ch);
  return f;
}
async function loadUserFont(rec){
  const f=makeUserFont(rec);
  if(rec.kind==='ttf'){
    f.family='PT_'+rec.id;
    const face=new FontFace(f.family,rec.files[0].buf);
    await face.load(); document.fonts.add(face);
  }else{
    f.pages=new Map();
    for(const file of rec.files){
      const bmp=await createImageBitmap(new Blob([file.buf],{type:'image/png'}));
      const c=document.createElement('canvas');c.width=bmp.width;c.height=bmp.height;
      const x=c.getContext('2d');x.drawImage(bmp,0,0);
      f.pages.set(file.page,{w:bmp.width,h:bmp.height,d:x.getImageData(0,0,bmp.width,bmp.height).data});
    }
  }
  FONTS.set(f.id,f); return f;
}
